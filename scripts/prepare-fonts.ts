import { readFile, readdir, rm } from 'node:fs/promises';
import { join } from 'node:path';
import subsetFont from 'subset-font';
import { writeFileAtomic } from '../lib/atomic-write';
import { fontFaceCss, notoFontFile, notoWeights, usedText } from '../lib/font-subset';

const fontPackage = '@expo-google-fonts/noto-sans-jp';
const weightNames: Record<(typeof notoWeights)[number], string> = { 400: 'Regular', 600: 'SemiBold' };
const outputDirectory = 'public/fonts';

async function sources(directory: string): Promise<string[]> {
  const entries = await readdir(directory, { withFileTypes: true });
  const result: string[] = [];
  for (const entry of entries) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) result.push(...await sources(path));
    else if (/\.(tsx?|css|md)$/.test(entry.name) && entry.name !== 'fonts.css') result.push(await readFile(path, 'utf8'));
  }
  return result;
}
const text = usedText((await Promise.all(['app', 'components', 'data'].map(sources))).flat().join('\n'));
const files = notoWeights.map(notoFontFile);

// 内容から外れた旧ファイルを残すと、参照されないフォントがデプロイされ続ける
for (const name of await readdir(outputDirectory)) {
  if (name.endsWith('.woff2') && !files.includes(name)) await rm(join(outputDirectory, name));
}
let bytes = 0;
for (const weight of notoWeights) {
  const name = `${weight}${weightNames[weight]}`;
  const source = await readFile(`node_modules/${fontPackage}/${name}/NotoSansJP_${name}.ttf`);
  const subset = await subsetFont(source, text, { targetFormat: 'woff2' });
  await writeFileAtomic(join(outputDirectory, notoFontFile(weight)), subset);
  bytes += subset.byteLength;
}
const manifest: unknown = JSON.parse(await readFile(`node_modules/${fontPackage}/package.json`, 'utf8'));
if (typeof manifest !== 'object' || manifest === null || !('version' in manifest) || typeof manifest.version !== 'string') {
  throw new Error(`${fontPackage}/package.json has no version`);
}
const { version } = manifest;
await writeFileAtomic(join(outputDirectory, 'files.json'), JSON.stringify({ package: `${fontPackage}@${version}`, weights: notoWeights, files }, null, 2) + '\n');
await writeFileAtomic('app/fonts.css', '/* Generated by bun run fonts:generate. Do not edit directly. */\n' + fontFaceCss(notoWeights));
console.log(`Fonts: ${[...text].length.toLocaleString()} characters, ${bytes.toLocaleString()} bytes of WOFF2 for the current content.`);
